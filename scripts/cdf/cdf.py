#!/usr/bin/env python3
"""The normal CDF and erfc dataset: every on-chain implementation at the same exact points, against mpmath.

    make cdf         # forge test Cdf -vv | this script -> docs/benchmarks/cdf.{json,md}
    make cdf-check   # fail if the committed dataset differs

Reads CDF|impl|op|k|raw|gas lines from test/cdf/Cdf.t.sol. Each point is x = k/32, exact in every representation,
so the error is the implementation's alone. The truth is mpmath at 150 digits. Per implementation and op it records
the largest absolute error, the correct digits (relative, floor(-log10 |v - t| / t), capped at 100) at every point,
their minimum and median, and the median gas of a call.
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

from mpmath import mp, mpf, ncdf, erfc, log10, nstr

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "ladder"))
from gen_inputs import fp19_decode  # noqa: E402

mp.dps = 150  # well past FP19's 71 digits, so its error is measured, not rounded away
OUT_JSON = ROOT / "docs" / "benchmarks" / "cdf.json"
OUT_MD = ROOT / "docs" / "benchmarks" / "cdf.md"
K = 192

# implementation -> (label, representation, source); the representation decodes the raw result
IMPLS = {
    "fp19": ("FP19", "FP19, 256-bit float", "contracts/src/fp19 (FP19Lib)"),
    "fp127": ("FP127", "FP127, 127.128 fixed point", "contracts/src/fp127 (FP127Lib)"),
    "solstat": ("solstat", "WAD (10^18)", "primitivefinance/solstat @ 80c603f, Gaussian.sol (lib/solstat)"),
    "lyra": ("Lyra v1", "10^27", "lyra-finance/lyra-protocol @ ea9e36a, BlackScholes._stdNormalCDF (vendored)"),
    "rmm": ("Primitive RMM-01", "ABDK 64.64", "primitivefinance/rmm-core @ 8d3ef9b, CumulativeNormalDistribution.getCDF (transcribed)"),
}
DECODE = {
    "fp19": fp19_decode,
    "fp127": lambda r: mpf(r) / mpf(2) ** 128,
    "solstat": lambda r: mpf(r) / mpf(10) ** 18,
    "lyra": lambda r: mpf(r) / mpf(10) ** 27,
    "rmm": lambda r: mpf(r) / mpf(2) ** 64,
}
TRUTH = {"normCdf": ncdf, "erfc": erfc}


def digits(v, t) -> int:
    if v == t:
        return 100
    if t == 0:
        return 0
    e = abs(v - t) / abs(t)
    return max(0, min(100, int(mp.floor(-log10(e)))))


def parse(lines) -> dict:
    cells = {}
    for line in lines:
        line = line.strip()
        if not line.startswith("CDF|"):
            continue
        _, impl, op, k, raw, gas = line.split("|")
        cells[(impl, op, int(k))] = (None if raw == "REVERT" else int(raw), int(gas))
    return cells


def build(cells: dict) -> dict:
    impls = []
    for impl, (label, rep, src) in IMPLS.items():
        ops = {}
        for op, f in TRUTH.items():
            pts, gas, worst = [], [], mpf(0)
            for k in range(-K, K + 1):
                c = cells.get((impl, op, k))
                if c is None:
                    continue
                raw, g = c
                x = mpf(k) / 32
                t = f(x)
                if raw is None:
                    pts.append({"k": k, "reverted": True})
                    continue
                v = DECODE[impl](raw)
                worst = max(worst, abs(v - t))
                pts.append({"k": k, "digits": digits(v, t)})
                gas.append(g)
            ds = [p["digits"] for p in pts if "digits" in p]
            if not ds:
                continue
            ops[op] = {"points": len(pts), "reverted": sum(1 for p in pts if p.get("reverted")),
                       "maxAbsErr": nstr(worst, 3) if worst else "0",
                       "digitsMin": min(ds), "digitsMedian": statistics.median(ds),
                       "gasMedian": int(statistics.median(gas)), "gasMax": max(gas),
                       "series": [[p["k"], p.get("digits")] for p in pts]}
        impls.append({"id": impl, "label": label, "representation": rep, "source": src, "ops": ops})
    return {"_doc": "Generated by scripts/cdf/cdf.py from test/cdf/Cdf.t.sol; do not edit.",
            "grid": {"x": "k/32", "kMin": -K, "kMax": K, "points": 2 * K + 1},
            "truth": "mpmath 150 digits: ncdf(x) and erfc(x) at the exact x",
            "implementations": impls}


def markdown(d: dict) -> str:
    out = ["# The normal CDF and erfc, every implementation", "",
           f"Each library's own code at x = k/32 for k = {d['grid']['kMin']} to {d['grid']['kMax']} ({d['grid']['points']} points on [-6, 6], "
           "exact in every representation), against mpmath at 150 digits. Digits are correct significant digits of the "
           "result; gas is the median of a call. Generated by `scripts/cdf/cdf.py` (`make cdf`).", ""]
    for op in TRUTH:
        out += [f"## {op}", "", "| implementation | representation | max abs error | digits (min) | digits (median) | gas (median) | gas (max) |",
                "|---|---|---:|---:|---:|---:|---:|"]
        for i in d["implementations"]:
            o = i["ops"].get(op)
            if o:
                out.append(f"| {i['label']} | {i['representation']} | {o['maxAbsErr']} | {o['digitsMin']} | {o['digitsMedian']:g} | {o['gasMedian']:,} | {o['gasMax']:,} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    d = build(parse(sys.stdin))
    js = json.dumps(d, indent=1) + "\n"
    md = markdown(d)
    if "--check" in argv:
        stale = [p.name for p, s in ((OUT_JSON, js), (OUT_MD, md)) if not p.exists() or p.read_text() != s]
        if stale:
            print("stale (run make cdf):", ", ".join(stale))
            return 1
        print("cdf dataset is current")
        return 0
    OUT_JSON.write_text(js)
    OUT_MD.write_text(md)
    print(f"wrote {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
