#!/usr/bin/env python3
"""Render docs/fp127/precision.md from docs/fp127/precision.json, which
test/fp127/Precision.t.sol writes on every run."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
import sys as _sys
LIB = "fp256" if "--lib" in _sys.argv and _sys.argv[_sys.argv.index("--lib") + 1] == "fp256" else "fp127"
SRC = ROOT / "docs" / LIB / "precision.json"
OUT = ROOT / "docs" / LIB / "precision.md"

ORDER_FP256 = ["add", "sub", "mul", "div", "sqrt", "exp", "ln", "pow", "log1p", "expm1", "erf", "erfc", "normCdf", "lambertW0", "lambertWm1", "powu", "compound", "neg", "abs", "sign", "cmp", "lt", "eq",
               "fromUint", "fromFP127", "toFP127", "fromFixed18", "toFixed18"]

ORDER = [
    "add", "sub", "mul", "mulDown", "mulUp", "div", "divDown", "divUp",
    "fromFixed18", "toFixed18", "toFixed18Down", "toFixed18Up",
    "exp", "exp2", "exp10", "ln", "log2", "log10", "log2Up",
    "sqrt", "cbrt", "pow", "inv", "abs", "neg", "sign", "min", "max", "clamp", "avg",
    "zeroFloorSub", "dist", "lerp", "floor", "ceil", "frac", "round", "gcd", "factorial",
    "hypot", "gavg", "lambertW0", "lambertWm1", "pi",
    "powu", "compound", "log1p", "expm1", "sinh", "cosh", "tanh", "atanh", "erf", "erfc", "normCdf",
]


def fmt_bits(b: int) -> str:
    return "exact" if b >= 255 else str(b)


def main() -> int:
    data = json.loads(SRC.read_text())
    order = ORDER_FP256 if LIB == "fp256" else ORDER
    if LIB == "fp127":
        return fp127(data)
    lines = [
        f"# {LIB.upper()} precision",
        "",
        (f"Generated by `make test` (test/fp256/Precision.t.sol) against exact rationals and mpmath at 300 decimal "
         "places (scripts/fp256/oracle.py), over the committed vectors in test/fp256/vectors/. "
         "Regenerate the table with `make precision-report-fp256`."
         if LIB == "fp256" else
         "Generated by `make test` (test/fp127/Precision.t.sol) against mpmath at 200 decimal "
         "places (scripts/fp127/oracle.py), over the committed vectors in test/fp127/vectors/. "
         "Regenerate the table with `make precision-report`."),
        "",
        ("Bits are relative correct bits of the result on the decoded values: the significands aligned at the larger exponent, msb(truth) - msb(|truth - got|). "
         if LIB == "fp256" else
         "Bits are relative correct bits of the 127.128 result: msb(|truth|) - msb(|truth - got|). ")
        + "\"exact\" means bit-identical, or within 2 ULP for an approximated op. "
        "`reverts` counts vectors where the oracle and the Yul both reject the input with the same error.",
        "",
        "| op | vectors | reverts | min bits | mean bits | worst input |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for op in order:
        e = data.get(op)
        if not e:
            continue
        worst = e.get("worstInput", "") or ""
        if worst:
            worst = "`" + worst.replace(",", "`, `") + "`"
        lines.append(f"| {op} | {e['n']} | {e.get('reverts', 0)} | {fmt_bits(int(e['minBits']))} | {fmt_bits(int(e['meanBits']))} | {worst} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


def fp127(data: dict) -> int:
    """The FP127 table: the true distance to the real truth, per rounding contract."""
    lines = [
        "# FP127 precision",
        "",
        "Generated by `make test` (test/fp127/Precision.t.sol) against mpmath at 200 decimal places "
        "(scripts/fp127/oracle.py), over the committed vectors in test/fp127/vectors/. Regenerate the "
        "table with `make precision-report`.",
        "",
        "Every vector carries the real truth, and the error is the true distance |got − truth| in ULPs "
        "(2^-128), measured to 2^-64 ULP. Each op is held to its rounding contract: *exact* 0, "
        "*floor*, *ceil* and *trunc* under 1 ULP in their direction, *nearest* at most 0.5 ULP (a directed op shows 1.0000 where its distance is within 2^-65 of one ULP). "
        "*sqrt of floors* (gavg, hypot, kept bit-identical to the Huff) must equal its definition, the "
        "floored root of a floored product or sum; its distance from the real root is shown, not bounded. "
        "*series* is pi's Ramanujan partial sum in integers. *nearest* counts results within 0.5 ULP. "
        "*min bits* is the fewest relative correct bits, msb(|truth|) − msb(|got − truth|), over results "
        "of magnitude 1 or more (\"exact\" when every such result is the truth itself). "
        "`reverts` counts vectors where the oracle and the Yul both reject the input with the same error.",
        "",
        "| op | rounding | vectors | reverts | max error (ULP) | nearest | min bits (≥ 1) | worst input |",
        "|---|---|---:|---:|---:|---:|---:|---|",
    ]
    for op in ORDER:
        e = data.get(op)
        if not e:
            continue
        worst = e.get("worstInput", "") or ""
        if worst:
            worst = "`" + worst.replace(",", "`, `") + "`"
        lines.append(f"| {op} | {e['rounding']} | {e['n']} | {e.get('reverts', 0)} | {e['maxErrUlp']} | "
                     f"{e['nearest']} | {fmt_bits(int(e['minBits']))} | {worst} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
