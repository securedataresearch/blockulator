#!/usr/bin/env python3
"""Gas of the osaka build against the shanghai build, per op.

    forge test --match-contract '^BenchOsaka$' -vv | uv run scripts/fp127/bench_osaka.py

Reads the OSAKA| lines of test/osaka/BenchOsaka.t.sol (make bench-osaka) and
writes docs/benchmarks/gas-osaka.json and gas-osaka.md. Both objects run on
the same osaka EVM with the same inputs, so the difference is the code: msb
(and FP256's ctz) on CLZ, and solc 0.8.38 in place of 0.8.24 with the same
optimizer sequence.
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "benchmarks"


def main() -> int:
    rows = []
    for line in sys.stdin:
        i = line.find("OSAKA|")
        if i < 0:
            continue
        lib, obj, op, n, shm, osm, sha, osa = line[i:].strip().split("|")[1:]
        rows.append({"lib": lib, "object": obj, "op": op, "n": int(n),
                     "shanghaiMedian": int(shm), "osakaMedian": int(osm),
                     "shanghaiMean": int(sha), "osakaMean": int(osa)})
    if not rows:
        sys.stderr.write("no OSAKA| lines on stdin\n")
        return 1
    (OUT / "gas-osaka.json").write_text(json.dumps(rows, indent=1) + "\n")

    def pct(a: int, b: int) -> str:
        return f"{100 * (b - a) / a:+.1f}%" if a else "-"

    md = ["# Gas: osaka build against shanghai build", "",
          "Generated by `make bench-osaka` (test/osaka/BenchOsaka.t.sol, scripts/fp127/bench_osaka.py).",
          "Each op runs on its committed precision vectors (or 64 inputs near one where it has none), on",
          "both objects, on the same osaka EVM; only inputs where both succeed count. Gas is the whole",
          "external call (dispatch included), warm. The osaka objects are the same source with msb (and",
          "FP256's ctz) on the CLZ opcode, compiled by solc 0.8.38 with 0.8.24's optimizer sequence.", ""]
    md += ["## Summary by object", "",
           "| object | ops | median saving | mean saving | largest saving | smallest saving |",
           "|---|---:|---:|---:|---:|---:|"]
    for obj in dict.fromkeys(r["object"] for r in rows):
        d = [r["shanghaiMedian"] - r["osakaMedian"] for r in rows if r["object"] == obj and r["n"]]
        if d:
            md.append(f"| {obj} | {len(d)} | {statistics.median(d):,.0f} | {statistics.mean(d):,.0f} | {max(d):,} | {min(d):,} |")
    for lib in dict.fromkeys(r["lib"] for r in rows):
        md += ["", f"## {lib.upper()}", "",
               "| op | object | inputs | shanghai median | osaka median | saving | change | shanghai mean | osaka mean |",
               "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for r in sorted((r for r in rows if r["lib"] == lib), key=lambda r: (r["object"], r["op"])):
            s, o = r["shanghaiMedian"], r["osakaMedian"]
            md.append(f"| {r['op']} | {r['object']} | {r['n']} | {s:,} | {o:,} | {s - o:,} | {pct(s, o)} "
                      f"| {r['shanghaiMean']:,} | {r['osakaMean']:,} |")
    (OUT / "gas-osaka.md").write_text("\n".join(md) + "\n")
    print(f"wrote docs/benchmarks/gas-osaka.json and gas-osaka.md ({len(rows)} ops)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
