#!/usr/bin/env python3
"""Generate scripts/ladder/edge-inputs.json from scripts/ladder/edges.json.

Every probe's arguments are evaluated exactly (mpmath at 200 digits; the
expressions may use e and pi) and encoded into each representation, as
gen_inputs.py does for the ladder: floored on a grid, nearest for
binary128. An integer argument (kind "n") is passed unscaled.

    uv run scripts/ladder/gen_edges.py          # write
    uv run scripts/ladder/gen_edges.py --check  # fail if stale
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from mpmath import mp, mpf, e, pi

from gen_inputs import SCALES, to_scaled

mp.dps = 200
ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "scripts" / "ladder" / "edges.json"
OUT = ROOT / "scripts" / "ladder" / "edge-inputs.json"


def ev(expr: str):
    """Evaluate an expression with every numeric literal as an mpf."""
    src = re.sub(r"(?<![\w.])(\d+\.?\d*(?:e-?\d+)?)", r"mpf('\1')", expr)
    return eval(src, {"mpf": mpf, "e": e, "pi": pi, "__builtins__": {}}, {})


def probe_id(p: dict) -> str:
    return f"{p['op']}({','.join(p['args'])})"


def build(spec: dict) -> dict:
    ops = {o["id"]: o for o in spec["ops"]}
    cells = []
    for p in spec["probes"]:
        op = ops[p["op"]]
        kinds = op["args"]
        if len(kinds) != len(p["args"]):
            raise SystemExit(f"{probe_id(p)}: {len(p['args'])} args, op takes {len(kinds)}")
        vals = [ev(a) for a in p["args"]]
        cell = {"id": probe_id(p), "op": op["id"], "opIndex": op["index"], "args": p["args"], "kinds": kinds, "why": p.get("why", "")}
        unrep = {}
        for name, (_, scale, (lo, hi)) in SCALES.items():
            ints = [int(v) if k == "n" else to_scaled(v, scale) for v, k in zip(vals, kinds)]
            cell[name] = [str(i) for i in ints]
            unrep[name] = any(i < lo or i > hi for i, k in zip(ints, kinds) if k != "n")
        cell["unrepresentable"] = unrep
        cells.append(cell)
    return {
        "_doc": "Generated by scripts/ladder/gen_edges.py from edges.json: every probe's arguments encoded into each representation, as decimal strings (an integer argument is unscaled). unrepresentable marks a value outside the representation's range; the harness records RANGE for it without calling.",
        "scales": {k: v[0] for k, v in SCALES.items()},
        "count": len(cells),
        "cells": cells,
    }


def main(argv: list[str]) -> int:
    doc = build(json.loads(SPEC.read_text()))
    text = json.dumps(doc, indent=1) + "\n"
    if "--check" in argv:
        if OUT.exists() and OUT.read_text() == text:
            print("gen-edges ok")
            return 0
        print("edge-inputs.json is stale; run `make gen-edges`", file=sys.stderr)
        return 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {doc['count']} probes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
